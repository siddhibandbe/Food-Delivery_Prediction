import streamlit as st
import pandas as pd
import joblib

# Load trained model
rf_model = joblib.load("rf_model.pkl")

# Page title
st.set_page_config(
    page_title="Food Delivery Time Prediction",
    page_icon="🍔"
)

st.title("🍔 Food Delivery Time Prediction")
st.write("Predict the estimated food delivery time using Random Forest.")

st.subheader("Enter Order Details")

# Input fields
Order_Hour = st.number_input(
    "Order Hour",
    min_value=0,
    max_value=23,
    value=19
)

Day_of_Week = st.selectbox(
    "Day of Week",
    ["Monday", "Tuesday", "Wednesday", "Thursday",
     "Friday", "Saturday", "Sunday"]
)

Is_Weekend = st.selectbox(
    "Is Weekend",
    [0, 1]
)

Weather = st.selectbox(
    "Weather",
    ["Clear", "Rainy", "Foggy", "Stormy"]
)

Vehicle_Type = st.selectbox(
    "Vehicle Type",
    ["Scooter", "Motorcycle", "Bicycle", "Car"]
)

Rider_Experience_Years = st.number_input(
    "Rider Experience (Years)",
    min_value=0.0,
    max_value=20.0,
    value=3.0
)

Rider_Rating = st.number_input(
    "Rider Rating",
    min_value=1.0,
    max_value=5.0,
    value=4.2
)

Restaurant_Rating = st.number_input(
    "Restaurant Rating",
    min_value=1.0,
    max_value=5.0,
    value=4.0
)

Order_Items = st.number_input(
    "Number of Order Items",
    min_value=1,
    max_value=20,
    value=2
)

Restaurant_Load = st.selectbox(
    "Restaurant Load",
    ["Low", "Medium", "High"]
)

Preparation_Time_Min = st.number_input(
    "Preparation Time (Minutes)",
    min_value=1,
    max_value=120,
    value=20
)

Road_Distance_km = st.number_input(
    "Road Distance (km)",
    min_value=0.1,
    max_value=100.0,
    value=8.5
)

Traffic_Level = st.selectbox(
    "Traffic Level",
    ["Low", "Moderate", "High"]
)

# Prediction button
if st.button("Predict Delivery Time"):

    # Create input dataframe
    new_order = pd.DataFrame({
        "Order_Hour": [Order_Hour],
        "Day_of_Week": [Day_of_Week],
        "Is_Weekend": [Is_Weekend],
        "Weather": [Weather],
        "Vehicle_Type": [Vehicle_Type],
        "Rider_Experience_Years": [Rider_Experience_Years],
        "Rider_Rating": [Rider_Rating],
        "Restaurant_Rating": [Restaurant_Rating],
        "Order_Items": [Order_Items],
        "Restaurant_Load": [Restaurant_Load],
        "Preparation_Time_Min": [Preparation_Time_Min],
        "Road_Distance_km": [Road_Distance_km],
        "Traffic_Level": [Traffic_Level]
    })

    # Predict
    predicted_time = rf_model.predict(new_order)

    # Display result
    st.success(
        f"Predicted Food Delivery Time: {predicted_time[0]:.2f} minutes"
    )